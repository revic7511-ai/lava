/* 직무 분류: 섹터별로 처음 일치한 대분류 1개씩 배정 (sectors가 없으면 제목 사용) */
window.classifyJob = function (job) {
  var texts = (job.sectors && job.sectors.length)
    ? job.sectors.slice()
    : [job.title || ""];
  var cats = [];

  texts.forEach(function (text) {
    var low = text.toLowerCase();
    for (var i = 0; i < window.FIELD_CATS.length; i++) {
      var cat = window.FIELD_CATS[i];
      var hit = cat.kw.some(function (kw) {
        if (kw.charAt(0) === "=") return text === kw.slice(1);
        return low.indexOf(kw.toLowerCase()) !== -1;
      });
      if (hit) {
        if (cats.indexOf(cat.name) === -1) cats.push(cat.name);
        break;
      }
    }
  });
  return cats;
};
